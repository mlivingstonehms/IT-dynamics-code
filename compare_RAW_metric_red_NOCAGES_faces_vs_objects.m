%% compare_RAW_metric_distributions_faces_vs_objects.m
%
% Compare the UNDERLYING RAW image-metric distributions for NO-CAGE images only:
%
%       FACES   = human faces + monkey faces + PPE faces
%       OBJECTS = object image set
%
% IMPORTANT:
% These are the original, non-rank-normalized image measurements.
% This script does NOT use neural responses and does NOT use time.
%
% Metrics:
%   1. Number of parts
%   2. Perimeter density
%   3. Normalized perimeter
%   4. Area fraction
%   5. Spatial frequency
%
% Spatial frequency has its own historical image-name list, so it is
% matched/classified by image name independently.
%
% Statistics reported for Faces and Objects:
%   N
%   mean
%   median
%   SD
%   IQR
%
% Two comparisons are also reported:
%   ranksum p              = difference in distributions/location
%   Brown-Forsythe p       = difference in spread/variance
%
% Figures:
%   1. Raw distributions: faces vs objects for all 5 metrics
%   2. SD comparison
%   3. IQR comparison
%
% ========================================================================

close all
clear all
clc


%% ========================================================================
% PATHS
% ========================================================================

metricFolder = ...
    '/n/data2/hms/neurobio/livingstone/marge/margemonkeys/chatmetricsEdges';

complexityFolder = ...
    '/n/data2/hms/neurobio/livingstone/marge/margemonkeys/complexities';

rootFolder = ...
    '/n/data2/hms/neurobio/livingstone/marge/margemonkeys';

saveFolder = ...
    '/n/data2/hms/neurobio/livingstone/marge/figimages/temp';


%% ========================================================================
% LOAD RAW IMAGE METRICS
% ========================================================================

load(fullfile(metricFolder,'numberparts.mat'));
load(fullfile(metricFolder,'manyOOimagename.mat'));
load(fullfile(metricFolder,'redCyanRatio_manyOO.mat'));
load(fullfile(metricFolder,'normalizedSilhouettePerimeter.mat'));
load(fullfile(metricFolder,'silhouetteAreaFraction.mat'));

load(fullfile(complexityFolder,'SpFq_manyOO.mat'));
load(fullfile(complexityFolder,'SpFqname_manyOO.mat'));


%% ========================================================================
% LOAD CATEGORY IMAGE LISTS
% ========================================================================

load(fullfile(rootFolder,'hfaceims.mat'));
load(fullfile(rootFolder,'mfaceims.mat'));
load(fullfile(rootFolder,'pfaceims.mat'));
load(fullfile(rootFolder,'objectims.mat'));


%% ========================================================================
% LOAD NO-CAGE IMAGE LIST
%
% Find all saved *_manyOOnocages_image_list.mat files and combine them.
% Only images present in at least one no-cage list are retained below.
% ========================================================================

noCageFiles = dir(fullfile(rootFolder,'**','*_manyOOnocages_image_list.mat'));

if isempty(noCageFiles)
    error(['Could not find any *_manyOOnocages_image_list.mat files under:\n' ...
           '%s'],rootFolder);
end

fprintf('\nFound %d no-cage image-list file(s):\n',numel(noCageFiles));

allNoCageNames = strings(0,1);

for k = 1:numel(noCageFiles)

    thisFile = fullfile(noCageFiles(k).folder,noCageFiles(k).name);
    fprintf('  %s\n',thisFile);

    S = load(thisFile);
    f = fieldnames(S);

    if isempty(f)
        warning('Skipping empty no-cage list file: %s',thisFile);
        continue
    end

    thisNames = S.(f{1});
    allNoCageNames = [allNoCageNames; cleanNames(thisNames)]; %#ok<AGROW>
end

allNoCageNames = unique(allNoCageNames);

fprintf('Unique no-cage image names found: %d\n',numel(allNoCageNames));


%% ========================================================================
% CLEAN IMAGE NAMES
% ========================================================================

masterNames = ...
    cleanNames(imageName);

sfNames = ...
    cleanNames(SFname);

hfaceName = ...
    cleanNames(hface);

mfaceName = ...
    cleanNames(mface);

pfaceName = ...
    cleanNames(Pface);

objectName = ...
    cleanNames(objectims);


%% ========================================================================
% DEFINE NO-CAGE MASKS FOR THE MAIN METRIC LIST AND SF LIST
% ========================================================================

isNoCage_master = ...
    ismember(masterNames,allNoCageNames);

isNoCage_SF = ...
    ismember(sfNames,allNoCageNames);

fprintf('\nNO-CAGE MATCHING\n');
fprintf('No-cage images in main metric list: %d / %d\n', ...
    sum(isNoCage_master),numel(masterNames));
fprintf('No-cage images in SF list:          %d / %d\n', ...
    sum(isNoCage_SF),numel(sfNames));


%% ========================================================================
% FORCE RAW METRICS TO COLUMN VECTORS
% ========================================================================

numberparts = ...
    double(numberparts(:));

normalizedSilhouettePerimeter = ...
    double(normalizedSilhouettePerimeter(:));

silhouetteAreaFraction = ...
    double(silhouetteAreaFraction(:));

redCyanRatio = ...
    double(redCyanRatio(:));

SF = ...
    double(SF(:));


%% ========================================================================
% CHECK MASTER-LIST ALIGNMENT FOR THE FOUR NON-SF METRICS
% ========================================================================

nMaster = ...
    numel(masterNames);


metricLengths = [ ...
    numel(numberparts), ...
    numel(normalizedSilhouettePerimeter), ...
    numel(silhouetteAreaFraction), ...
    numel(redCyanRatio), ...
    numel(SF)];


if any(metricLengths ~= nMaster)

    error(['The four main raw metric vectors do not all match imageName. ' ...
        'imageName=%d, Parts=%d, SilDensity=%d, NormPerim=%d, AreaFrac=%d'], ...
        nMaster, ...
        metricLengths(1), ...
        metricLengths(2), ...
        metricLengths(3), ...
        metricLengths(4), ...
        metricLengths(5));

end


if numel(SF) ~= numel(sfNames)

    error('SF and SFname have different lengths: SF=%d, SFname=%d.', ...
        numel(SF),numel(sfNames));

end


%% ========================================================================
% DEFINE FACES AND OBJECTS
%
% Faces = human face OR monkey face OR PPE face
% ========================================================================

isFace_master = ...
    isNoCage_master & ( ...
    ismember(masterNames,hfaceName) | ...
    ismember(masterNames,mfaceName) | ...
    ismember(masterNames,pfaceName));


isObject_master = ...
    isNoCage_master & ismember(masterNames,objectName);


isFace_SF = ...
    isNoCage_SF & ( ...
    ismember(sfNames,hfaceName) | ...
    ismember(sfNames,mfaceName) | ...
    ismember(sfNames,pfaceName));


isObject_SF = ...
    isNoCage_SF & ismember(sfNames,objectName);


fprintf('\nNO-CAGE IMAGE CLASSIFICATION\n');
fprintf('Faces in main metric list:   %d\n',sum(isFace_master));
fprintf('Objects in main metric list: %d\n',sum(isObject_master));
fprintf('Faces in SF list:            %d\n',sum(isFace_SF));
fprintf('Objects in SF list:          %d\n',sum(isObject_SF));


%% ========================================================================
% ASSEMBLE RAW FACE AND OBJECT VALUES
% ========================================================================

metricNames = { ...
    'Number of parts', ...
    'Normalized perimeter', ...
    'Area fraction', ...
    'redCyanRatio', ...
    'Spatial frequency'};

nMetrics = ...
    numel(metricNames);


faceValues = ...
    cell(nMetrics,1);

objectValues = ...
    cell(nMetrics,1);


%% Number of parts

faceValues{1} = ...
    numberparts(isFace_master & isfinite(numberparts));

objectValues{1} = ...
    numberparts(isObject_master & isfinite(numberparts));


%% Perimeter density

faceValues{2} = ...
    normalizedSilhouettePerimeter(isFace_master & isfinite(normalizedSilhouettePerimeter));

objectValues{2} = ...
    normalizedSilhouettePerimeter(isObject_master & isfinite(normalizedSilhouettePerimeter));


%% Normalized perimeter

faceValues{3} = ...
    silhouetteAreaFraction( ...
    isFace_master & isfinite(silhouetteAreaFraction));

objectValues{3} = ...
    silhouetteAreaFraction( ...
    isObject_master & isfinite(silhouetteAreaFraction));


%% Area fraction

faceValues{4} = ...
    silhouetteAreaFraction( ...
    isFace_master & isfinite(silhouetteAreaFraction));

objectValues{4} = ...
    redCyanRatio( ...
    isObject_master & isfinite(redCyanRatio));


%% Spatial frequency -- use its own name list

faceValues{5} = ...
    SF(isFace_SF & isfinite(SF));

objectValues{5} = ...
    SF(isObject_SF & isfinite(SF));


%% ========================================================================
% SUMMARY STATISTICS
% ========================================================================

faceN = ...
    nan(nMetrics,1);

objectN = ...
    nan(nMetrics,1);

faceMean = ...
    nan(nMetrics,1);

objectMean = ...
    nan(nMetrics,1);

faceMedian = ...
    nan(nMetrics,1);

objectMedian = ...
    nan(nMetrics,1);

faceSD = ...
    nan(nMetrics,1);

objectSD = ...
    nan(nMetrics,1);

faceIQR = ...
    nan(nMetrics,1);

objectIQR = ...
    nan(nMetrics,1);

rankSumP = ...
    nan(nMetrics,1);

brownForsytheP = ...
    nan(nMetrics,1);


for m = 1:nMetrics

    f = ...
        double(faceValues{m}(:));

    o = ...
        double(objectValues{m}(:));


    f = ...
        f(isfinite(f));

    o = ...
        o(isfinite(o));


    faceN(m) = ...
        numel(f);

    objectN(m) = ...
        numel(o);


    faceMean(m) = ...
        mean(f);

    objectMean(m) = ...
        mean(o);


    faceMedian(m) = ...
        median(f);

    objectMedian(m) = ...
        median(o);


    faceSD(m) = ...
        std(f);

    objectSD(m) = ...
        std(o);


    faceIQR(m) = ...
        iqr(f);

    objectIQR(m) = ...
        iqr(o);


    %% Distribution/location comparison

    rankSumP(m) = ...
        ranksum(f,o);


    %% Brown-Forsythe spread comparison
    %
    % More robust to non-normality than a classical F-test.

    y = [ ...
        f; ...
        o];


    group = [ ...
        repmat("Faces",numel(f),1); ...
        repmat("Objects",numel(o),1)];


    brownForsytheP(m) = ...
        vartestn( ...
        y, ...
        categorical(group), ...
        'TestType','BrownForsythe', ...
        'Display','off');

end


summaryTable = table( ...
    metricNames(:), ...
    faceN, ...
    objectN, ...
    faceMean, ...
    objectMean, ...
    faceMedian, ...
    objectMedian, ...
    faceSD, ...
    objectSD, ...
    faceIQR, ...
    objectIQR, ...
    rankSumP, ...
    brownForsytheP, ...
    'VariableNames', { ...
    'Metric', ...
    'FaceN', ...
    'ObjectN', ...
    'FaceMean', ...
    'ObjectMean', ...
    'FaceMedian', ...
    'ObjectMedian', ...
    'FaceSD', ...
    'ObjectSD', ...
    'FaceIQR', ...
    'ObjectIQR', ...
    'RankSumP', ...
    'BrownForsytheP'});


disp(' ')
disp('RAW IMAGE-METRIC DISTRIBUTIONS: NO-CAGE FACES VS OBJECTS')
disp(summaryTable)


%% ========================================================================
% ALSO PRINT SPREAD RATIOS
%
% >1 means Objects are more variable than Faces.
% ========================================================================

sdRatio_ObjectOverFace = ...
    objectSD ./ faceSD;

iqrRatio_ObjectOverFace = ...
    objectIQR ./ faceIQR;


spreadTable = table( ...
    metricNames(:), ...
    faceSD, ...
    objectSD, ...
    sdRatio_ObjectOverFace, ...
    faceIQR, ...
    objectIQR, ...
    iqrRatio_ObjectOverFace, ...
    brownForsytheP, ...
    'VariableNames', { ...
    'Metric', ...
    'FaceSD', ...
    'ObjectSD', ...
    'ObjectOverFace_SD_Ratio', ...
    'FaceIQR', ...
    'ObjectIQR', ...
    'ObjectOverFace_IQR_Ratio', ...
    'BrownForsytheP'});


disp(' ')
disp('SPREAD COMPARISON')
disp(spreadTable)


%% ========================================================================
% FIGURE 1
% RAW DISTRIBUTIONS
%
% Individual points are jittered horizontally.
% Boxcharts summarize the distributions.
% ========================================================================

figDist = ...
    figure( ...
    'Units','pixels', ...
    'Position',[100 80 1200 800], ...
    'Color','w', ...
    'Name','Raw image-metric distributions: no-cage faces vs no-cage objects', ...
    'NumberTitle','off');


movegui(figDist,'center');


tl = ...
    tiledlayout( ...
    figDist, ...
    2,3, ...
    'TileSpacing','loose', ...
    'Padding','compact');


rng(1);  % reproducible jitter


for m = 1:nMetrics

    ax = ...
        nexttile(tl,m);


    hold(ax,'on');


    f = ...
        faceValues{m}(:);

    o = ...
        objectValues{m}(:);




   %% Jittered individual image values

jitterWidth = 0.10;

xF = 1 + (rand(size(f))-0.5)*2*jitterWidth;
xO = 2 + (rand(size(o))-0.5)*2*jitterWidth;

% Colors
faceColor   = [1 0 0];          % red
objectColor = [0 0.75 0.90];    % cyan


%% Individual images

scatter( ...
    ax, ...
    xF, ...
    f, ...
    10, ...
    'filled', ...
    'MarkerFaceColor',faceColor, ...
    'MarkerEdgeColor',faceColor, ...
    'MarkerFaceAlpha',0.12, ...
    'MarkerEdgeAlpha',0.12);

scatter( ...
    ax, ...
    xO, ...
    o, ...
    10, ...
    'filled', ...
    'MarkerFaceColor',objectColor, ...
    'MarkerEdgeColor',objectColor, ...
    'MarkerFaceAlpha',0.12, ...
    'MarkerEdgeAlpha',0.12);


%% Box summaries

allVals = [f; o];

allGroups = [ ...
    ones(numel(f),1); ...
    2*ones(numel(o),1)];


bc = boxchart( ...
    ax, ...
    allGroups, ...
    allVals, ...
    'BoxWidth',0.35, ...
    'MarkerStyle','none');

% Make box summaries black and prominent
bc.BoxFaceColor = [0 0 0];
bc.BoxFaceAlpha = 0.05;
bc.WhiskerLineColor = [0 0 0];
bc.LineWidth = 2.5;


%% Means and connecting line

faceMean   = mean(f,'omitnan');
objectMean = mean(o,'omitnan');

% Line connecting the two means
plot( ...
    ax, ...
    [1 2], ...
    [faceMean objectMean], ...
    'k-', ...
    'LineWidth',3);

% Mean markers
plot( ...
    ax,1,faceMean,'o', ...
    'Color','k', ...
    'MarkerFaceColor',faceColor, ...
    'MarkerSize',10, ...
    'LineWidth',2);

plot( ...
    ax,2,objectMean,'o', ...
    'Color','k', ...
    'MarkerFaceColor',objectColor, ...
    'MarkerSize',10, ...
    'LineWidth',2);


%% Publication display limits
% These affect plotting ONLY, not any calculations.

switch m

    case 1      % Number of parts
        ylim(ax,[0 100]);

    case 2      % Normalized perimeter
        ylim(ax,[0 20]);

    case 3      % Area fraction
        ylim(ax,[0 1]);

    case 4      % Red/cyan ratio
        ylim(ax,[0 1.5]);

    case 5      % Spatial frequency
        ylim(ax,[0 5]);

end


%% Labels and publication formatting

xlim(ax,[0.5 2.5]);

xticks(ax,[1 2]);
xticklabels(ax,{'Faces','Objects'});
xtickangle(ax,0);     % <-- make them horizontal

ylabel(ax,'Raw metric value');

title( ...
    ax, ...
    metricNames{m}, ...
    'FontWeight','bold');

box(ax,'on');

set( ...
    ax, ...
    'LineWidth',2, ...
    'FontSize',16, ...
    'TickDir','out');

ax.Title.FontSize = 12;
ax.XLabel.FontSize = 16;
ax.YLabel.FontSize = 14;


end   % for m = 1:nMetrics



