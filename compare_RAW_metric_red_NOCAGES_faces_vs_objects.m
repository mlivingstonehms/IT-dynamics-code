%% ========================================================================
% LOCAL FUNCTION
% ========================================================================

function s = cleanNames(x)

    s = string(x(:));

    for ii = 1:numel(s)

        thisName = s(ii);


        slash = strfind(thisName,'/');

        if ~isempty(slash)

            thisName = ...
                extractAfter(thisName,slash(end));

        end


        slash = strfind(thisName,'\');

        if ~isempty(slash)

            thisName = ...
                extractAfter(thisName,slash(end));

        end


        s(ii) = thisName;

    end

end
