    title( ...
        ax, ...
        datasetNames{pop}, ...
        'Interpreter','none', ...
        'FontWeight','bold');


    box(ax,'on');

    set( ...
        ax, ...
        'LineWidth',1.5, ...
        'FontSize',10, ...
        'TickDir','out');

end


title( ...
    tlPop, ...
    'Temporal centroids of rank-normalized image metrics', ...
    'FontSize',14, ...
    'FontWeight','bold');


