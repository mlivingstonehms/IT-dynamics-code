%% partsSilSFCat_centroids_nocages.m
%
% Plot previously calculated temporal centroids of image metrics.
%
% Centroids are loaded directly from each *_rank_nocages.mat file.
%
% Metrics:
%   1. Number of parts
%   2. Perimeter density
%   3. Normalized perimeter
%   4. Area fraction
%   5. Spatial frequency
%   6. Category
%   7. Exemplar
%
% Also loads PSTHCentroid for comparison.
%
% IMPORTANT:
% This script assumes the centroid variables have ALREADY been calculated
% in the individual population scripts and saved in the *_rank_nocages.mat
% files. It does not recalculate or renormalize them.

close all
clearvars
clc


%% ================================================================
% PATHS
% ================================================================

dataFolder = ...
    '/n/data2/hms/neurobio/livingstone/marge/margemonkeys/chatmetricsEdges/data';

saveFolder = ...
    '/n/data2/hms/neurobio/livingstone/marge/figimages/temp';

if ~exist(saveFolder,'dir')
    mkdir(saveFolder);
end


%% ================================================================
% DATASET NAMES
% ================================================================

datasetNames = { ...
    'baby5_221104'
    'paul_230204'
    'paul_220428'
    'baby1_220226'
    'baby1_230629'
    'red_220227'};

nPopulations = numel(datasetNames);


%% ================================================================
% METRIC DEFINITIONS
% ================================================================

metricNames = { ...
    'Area fraction', ...
    'colorness', ...
    'Spatial frequency', ...
    'Number of parts', ...
    'Perimeter density', ...
    'Category', ...
    'Exemplar5'};

shortMetricNames = { ...
    'Area fraction', ...
         'colorness', ...
    'Spatial freq', ...
    'Parts', ...
    'Perim density', ...
    'Category', ...
    'Exemplar5'};

nMetrics = numel(metricNames);


%% ================================================================
% STORAGE
% ================================================================

allCentroids = nan(nPopulations,nMetrics);
psthCentroid = nan(nPopulations,1);

%% Peak-time storage

allPeaks = nan(nPopulations,nMetrics);
psthPeak = nan(nPopulations,1);
%% ================================================================
% LOAD CENTROIDS
% ================================================================

for pop = 1:nPopulations

    name = datasetNames{pop};

    rankFile = fullfile( ...
        dataFolder, ...
        [name '_rank_nocages.mat']);

    if ~exist(rankFile,'file')
        error('Cannot find file:\n%s',rankFile);
    end

    D = load(rankFile);

    %% Convert saved bin positions to normalized response time

nT = length(D.rasterchunkperpsth);

binToNorm = @(b) (double(b)-1) ./ (nT-1);

    %% Make sure peak variables are present

requiredPeakVars = { ...
    'partsX', ...
    'perimX', ...
    'areaX', ...
    'colorX', ...
    'sfX', ...
    'catX', ...
    'exempX', ...
    'psthX'};

for vv = 1:numel(requiredPeakVars)

    if ~isfield(D,requiredPeakVars{vv})
        error('%s is missing peak variable "%s".', ...
            rankFile,requiredPeakVars{vv});
    end
end

    %% Make sure all centroid variables are present

    requiredVars = { ...
        'partsCentroid', ...
        'perimeterCentroid', ...
        'areaCentroid', ...
        'colorCentroid', ...
        'sfCentroid', ...
        'categoryCentroid', ...
        'exemplar5Centroid', ...
        'PSTHCentroid'};

    for vv = 1:numel(requiredVars)

        if ~isfield(D,requiredVars{vv})

            error( ...
                '%s is missing variable "%s".', ...
                rankFile,requiredVars{vv});
        end
    end

    %% Store normalized metric peak times

allPeaks(pop,:) = [ ...
    binToNorm(D.areaX), ...
    binToNorm(D.colorX), ...
    binToNorm(D.sfX), ...
    binToNorm(D.partsX), ...
    binToNorm(D.perimX), ...
    binToNorm(D.catX), ...
    binToNorm(D.exempX)];

psthPeak(pop) = binToNorm(D.psthX);

    %% Store metric centroids
allCentroids(pop,:) = [ ...
    binToNorm(D.areaCentroid), ...
    binToNorm(D.colorCentroid), ...
    binToNorm(D.sfCentroid), ...
    binToNorm(D.partsCentroid), ...
    binToNorm(D.perimeterCentroid), ...
    binToNorm(D.categoryCentroid), ...
    binToNorm(D.exemplar5Centroid)];

psthCentroid(pop) = ...
    binToNorm(D.PSTHCentroid);


    fprintf('\n%s\n',name);

    fprintf('    PSTH centroid = %.3f\n', ...
        psthCentroid(pop));

    for metricIndex = 1:nMetrics

        fprintf('    %-22s = %.3f\n', ...
            metricNames{metricIndex}, ...
            allCentroids(pop,metricIndex));
    end

end


%% ================================================================
% DISPLAY TABLE
% ================================================================

centroidTable = array2table( ...
    allCentroids, ...
    'VariableNames', { ...
     'AreaFraction', ...
        'colorness', ...
        'SpatialFrequency', ...
        'NumberParts', ...
        'PerimeterDensity', ...
        'Category', ...
        'Exemplar5'});

centroidTable.Dataset = ...
    string(datasetNames);

centroidTable.PSTH = ...
    psthCentroid;

% Put Dataset first and PSTH second

centroidTable = movevars( ...
    centroidTable, ...
    {'Dataset','PSTH'}, ...
    'Before',1);

disp(' ')
disp('CENTROID TABLE')
disp(centroidTable)


%% ================================================================
% COMMON Y RANGE
%
% Do NOT force the upper limit to 1.
% Values > 1 are meaningful if the metric centroid occurs after
% the nominal PSTH-response interval.
% ================================================================

allValues = [ ...
    allCentroids(:); ...
    psthCentroid(:); ...
    0; ...
    1];

allValues = allValues(isfinite(allValues));

yMin = min(allValues);
yMax = max(allValues);

yPad = 0.08 * max(yMax-yMin,eps);

commonYLim = [ ...
    yMin-yPad, ...
    yMax+yPad];


%% ================================================================
% FIGURE 1
%
% ONE PANEL PER METRIC
% SIX POPULATIONS + PSTH CENTROID
% ================================================================

figMetric = figure( ...
    'Units','pixels', ...
    'Position',[200 50 1100 600], ...
    'Color','w', ...
    'Name','Centroids by metric', ...
    'NumberTitle','off');

movegui(figMetric,'center');

tlMetric = tiledlayout( ...
    figMetric,2,4, ...
    'TileSpacing','compact', ...
    'Padding','compact');


for metricIndex = 1:nMetrics

    ax = nexttile(tlMetric,metricIndex);

    hold(ax,'on');


    %% Reference: beginning and end of PSTH interval

    yline( ...
        ax,0,'--', ...
        'Color',[0.65 0.65 0.65], ...
        'LineWidth',1, ...
        'HandleVisibility','off');

    yline( ...
        ax,1,'--', ...
        'Color',[0.35 0.35 0.35], ...
        'LineWidth',1.5, ...
        'HandleVisibility','off');


    %% Connect each population's PSTH centroid to metric centroid

    for pop = 1:nPopulations

        plot( ...
            ax, ...
            [1 2], ...
            [psthCentroid(pop) ...
             allCentroids(pop,metricIndex)], ...
            '-', ...
            'Color',[0.75 0.75 0.75], ...
            'LineWidth',1.2);

        plot( ...
            ax,1,psthCentroid(pop), ...
            'ko', ...
            'MarkerFaceColor','k', ...
            'MarkerSize',6);

        plot( ...
            ax,2,allCentroids(pop,metricIndex), ...
            'o', ...
            'Color',[0.6350 0.0780 0.1840], ...
            'MarkerFaceColor',[0.6350 0.0780 0.1840], ...
            'MarkerSize',7);
    end


    xlim(ax,[0.5 2.5]);

    xticks(ax,[1 2]);

    xticklabels(ax,{ ...
        'PSTH', ...
        'Metric'});

    ylim(ax,commonYLim);

    ylabel(ax,'Normalized centroid time');

    title( ...
        ax, ...
        metricNames{metricIndex}, ...
        'FontWeight','bold');

    box(ax,'on');

    set( ...
        ax, ...
        'LineWidth',1.5, ...
        'FontSize',10, ...
        'TickDir','out');

end


title( ...
    tlMetric, ...
    'Temporal centroids of image metrics relative to PSTH centroid', ...
    'FontSize',14, ...
    'FontWeight','bold');


