% This script does NOT rank the timecourse again and does NOT min-max normalize it.
%
% Metrics:
%   1. Number of parts
%   2. Perimeter density
%   3. Normalized perimeter
%   4. Area fraction
%   5. Spatial frequency
%   6. category
%   7. exemplar
%
% Outputs:
%   Figure 1 = detected PSTH peak for each population
%   Figure 2 = one slope panel per metric
%   Figure 3 = five metric slopes within each population
%   Figure 4 = clustered color-coded population summary
%
% Also saves numerical slope results and confidence intervals.

