%% ================================================================
% CALCULATE SLOPES FOR EACH METRIC
% ================================================================

for metricIndex = 1:nMetrics

    Metric = metricData{metricIndex};

    metricSlopes     = nan(nPopulations,1);
    metricSlopeLower = nan(nPopulations,1);
    metricSlopeUpper = nan(nPopulations,1);

    allTime       = [];
    allMetric     = [];
    allPopulation = [];


    %% ------------------------------------------------------------
    % SIX POPULATIONS
    % ------------------------------------------------------------

    for pop = 1:nPopulations

        yFull = ...
            double(Metric{pop}(:));

        peakBin = ...
            psthPeakBin(pop);


        %% --------------------------------------------------------
        % KEEP ENTIRE SAVED / CLIPPED INTERVAL
        % ---------------------------------------------------------

        y = ...
            yFull(peakBin:end);


        %% --------------------------------------------------------
        % NORMALIZE POST-PEAK INTERVAL TO 0-1
        % ---------------------------------------------------------

        t = ...
            linspace(0,1,numel(y))';


        good = ...
            isfinite(t) & ...
            isfinite(y);

        t = t(good);
        y = y(good);


        if numel(y) < 3

            warning('%s %s has fewer than 3 post-peak bins.', ...
                datasetNames{pop}, ...
                metricNames{metricIndex});

            continue

        end


        %% --------------------------------------------------------
        % FIT LINE
        % ---------------------------------------------------------

        mdl = fitlm(t,y);


        metricSlopes(pop) = ...
            mdl.Coefficients.Estimate(2);


        ci = coefCI( ...
            mdl,0.05);

        metricSlopeLower(pop) = ...
            ci(2,1);

        metricSlopeUpper(pop) = ...
            ci(2,2);


        fprintf('%s | %-22s | start bin %d -> end | n=%d | slope=%.4f\n', ...
            datasetNames{pop}, ...
            metricNames{metricIndex}, ...
            peakBin, ...
            numel(y), ...
            metricSlopes(pop));


        %% Long-format arrays for LME

        allTime = [ ...
            allTime; ...
            t];

        allMetric = [ ...
            allMetric; ...
            y];

        allPopulation = [ ...
            allPopulation; ...
            repmat(pop,numel(y),1)];

    end


    %% ------------------------------------------------------------
    % SAVE POPULATION SLOPES
    % ------------------------------------------------------------

    allSlopes(:,metricIndex) = ...
        metricSlopes;

    allSlopeLower(:,metricIndex) = ...
        metricSlopeLower;

    allSlopeUpper(:,metricIndex) = ...
        metricSlopeUpper;


    %% ------------------------------------------------------------
    % MIXED-EFFECTS MODEL
    % ------------------------------------------------------------

    tbl = table( ...
        allTime, ...
        allMetric, ...
        categorical(allPopulation), ...
        'VariableNames', ...
        {'ResponseTime','MetricValue','Population'});


    lme = fitlme( ...
        tbl, ...
        'MetricValue ~ ResponseTime + (ResponseTime|Population)', ...
        'FitMethod','REML');


    coefTable = ...
        lme.Coefficients;


    timeRow = ...
        strcmp( ...
        coefTable.Name, ...
        'ResponseTime');


    beta = ...
        coefTable.Estimate(timeRow);

    lowerCI = ...
        coefTable.Lower(timeRow);

    upperCI = ...
        coefTable.Upper(timeRow);

    pValue = ...
        coefTable.pValue(timeRow);


    mixedBeta(metricIndex) = beta;
    mixedLower(metricIndex) = lowerCI;
    mixedUpper(metricIndex) = upperCI;
    mixedP(metricIndex) = pValue;


    %% ------------------------------------------------------------
    % PLOT METRIC PANEL
    % ------------------------------------------------------------

    ax = nexttile( ...
        tl,metricIndex);

    hold(ax,'on');


    yline( ...
        ax,0,'--', ...
        'LineWidth',1.5, ...
        'HandleVisibility','off');


    xPopulation = ...
        1:nPopulations;


    errorbar( ...
        ax, ...
        xPopulation, ...
        metricSlopes, ...
        metricSlopes-metricSlopeLower, ...
        metricSlopeUpper-metricSlopes, ...
        'o', ...
        'LineStyle','none', ...
        'LineWidth',2, ...
        'CapSize',10, ...
        'MarkerSize',7, ...
        'Color','k', ...
        'MarkerFaceColor','k', ...
        'MarkerEdgeColor','k');


    %% Mixed-effects point

    xLME = 7.5;

    errorbar( ...
        ax, ...
        xLME, ...
        beta, ...
        beta-lowerCI, ...
        upperCI-beta, ...
        'o', ...
        'LineStyle','none', ...
        'Color',[0.6350 0.0780 0.1840], ...
        'MarkerFaceColor',[0.6350 0.0780 0.1840], ...
        'MarkerEdgeColor',[0.6350 0.0780 0.1840], ...
        'LineWidth',3, ...
        'CapSize',14, ...
        'MarkerSize',13);


    xlim(ax,[0.3 8.2]);

    xticks(ax,[1:6 7.5]);

    xticklabels(ax,{ ...
        '1','2','3','4','5','6','LME'});

    xlabel(ax,'Population');

    ylabel( ...
        ax, ...
        yAxisNames{metricIndex});

    title( ...
        ax, ...
        metricNames{metricIndex}, ...
        'FontWeight','bold');


    box(ax,'on');

    set( ...
        ax, ...
        'LineWidth',2, ...
        'FontSize',11, ...
        'TickDir','out');


    %% Y limits

    yValues = [ ...
        metricSlopeLower; ...
        metricSlopeUpper; ...
        lowerCI; ...
        upperCI; ...
        0];

    yMin = min(yValues);
    yMax = max(yValues);

    yPad = ...
        0.12 * ...
        max(yMax-yMin,eps);

    ylim( ...
        ax, ...
        [yMin-yPad yMax+yPad]);


    %% Beta and p

    yl = ylim(ax);

    text( ...
        ax, ...
        0.55, ...
        yl(2)-0.06*range(yl), ...
        { ...
        sprintf('\\beta = %.3g',beta), ...
