% Each file must contain:
%   rasterchunkperpsth
%   rasterchunkbyimageperpsth
%   namebyimage
%   numpartsperpsth
%   silhouetteityperpsth
%   perityperpsth
%   AFityperpsth
%   SFityperpsth
