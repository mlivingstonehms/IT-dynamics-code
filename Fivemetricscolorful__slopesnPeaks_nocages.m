%
% The metric timecourses are means of ONCE rank-normalized per-image
% metrics. There is NO temporal min-max normalization in these files.
% ================================================================

for pop = 1:nPopulations

    name = datasetNames{pop};

    rankFile = fullfile( ...
        dataFolder, ...
        [name '_rank_slopes3.mat']);

    if ~exist(rankFile,'file')
        error('Cannot find unified rank file:\n%s',rankFile);
    end

    D = load(rankFile);

    requiredVars = { ...
        'rasterchunkperpsth', ...
        'rasterchunkbyimageperpsth', ...
        'namebyimage', ...
        'numpartsperpsth', ...
        'perityperpsth', ...
        'AFityperpsth', ...
         'colornessperpsth', ...
        'SFityperpsth', ...
        'numims'};

    for vv = 1:numel(requiredVars)
        if ~isfield(D,requiredVars{vv})
            error('%s is missing variable "%s".', ...
                rankFile,requiredVars{vv});
        end
    end

    PSTH{pop}     = double(D.rasterchunkperpsth(:));
    NumParts{pop} = double(D.numpartsperpsth(:));
    Peri{pop}     = double(D.perityperpsth(:));
    AF{pop}       = double(D.AFityperpsth(:));
    color{pop}       = double(D.colornessperpsth(:));
    SF{pop}       = double(D.SFityperpsth(:));
   

    %% Check that all saved timecourses are aligned

    nBins = [ ...
        numel(AF{pop}), ...
        numel(SF{pop}), ...
        numel(color{pop}), ...
        numel(NumParts{pop}), ...
        numel(Peri{pop}), ...
        numel(PSTH{pop}), ...
        size(D.rasterchunkbyimageperpsth,1)];

    if numel(unique(nBins)) ~= 1
        error(['Dataset %s has unequal time lengths: ' ...
            'AF=%d SF=%d Parts=%d Sil=%d Peri=%d PSTH=%d ' ...
            'ResponseByImage=%d'], ...
            name, ...
            nBins(1),nBins(2),nBins(3),nBins(4), ...
            nBins(5),nBins(6),nBins(7),nBins(8));
    end

    %% Check image names against response matrix columns

    if size(D.rasterchunkbyimageperpsth,2) ~= numel(D.namebyimage)
        error(['Dataset %s: rasterchunkbyimageperpsth has %d image columns ' ...
            'but namebyimage contains %d names.'], ...
            name, ...
            size(D.rasterchunkbyimageperpsth,2), ...
            numel(D.namebyimage));
    end

    fprintf('%s: %d aligned 5-ms bins | %d images | numims=%d\n', ...
        name,nBins(1),numel(D.namebyimage),double(D.numims));

    %% Confirm expected rank-normalized scale

    metricCheck = { ...
        AF{pop}, ...
         color{pop}, ...
        SF{pop}, ...
        NumParts{pop}, ...
        Peri{pop} ...
        };

    metricCheckNames = { ...
        'AreaFraction','SpatialFrequency','colorness', ...
        'NumberParts','NormalizedPerimeter' ...
        };

    for mm = 1:numel(metricCheck)

        xx = double(metricCheck{mm}(:));
        xx = xx(isfinite(xx));

        if ~isempty(xx) && (min(xx) < -1e-8 || max(xx) > 1+1e-8)

            warning(['%s %s is outside 0-1. ' ...
                'Check that this unified file was saved after per-image ' ...
                'rank normalization and BEFORE temporal min-max normalization.'], ...
                name,metricCheckNames{mm});

        end
    end
allPeaks(pop,:) = [ ...
